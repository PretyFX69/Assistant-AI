/* ============================================================
   Pretvfx-Tools — Ngaji (114 Surah + Audio Murottal)
   Data ada di tools/ngaji-data.js (window.PFX_NGAJI_DATA) — WAJIB
   dimuat SEBELUM file ini di index.html. Audio CDN publik, tanpa
   backend/API key sama sekali.
   ============================================================ */
(function () {
  'use strict';

  const state = { list: [], filtered: [], idx: -1, audio: null };

  function esc(s) {
    return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  }

  function fmtTime(sec) {
    if (!sec || isNaN(sec)) return '0:00';
    const m = Math.floor(sec / 60), s = Math.floor(sec % 60);
    return m + ':' + (s < 10 ? '0' + s : s);
  }

  function shellHtml() {
    return `
      <div class="pfx-ngaji-searchrow">
        <i class="fa-solid fa-magnifying-glass"></i>
        <input id="pfxNgajiSearch" class="pfx-ngaji-search" type="text" placeholder="Cari surah (nama / nomor)..." />
      </div>
      <div id="pfxNgajiList" class="pfx-ngaji-list"></div>
      <div id="pfxNgajiPlayer" class="pfx-ngaji-player" style="display:none;">
        <div class="pfx-ngaji-player-top">
          <div class="pfx-ngaji-player-info">
            <div class="pfx-ngaji-player-name" id="pfxNgajiPName">—</div>
            <div class="pfx-ngaji-player-arab" id="pfxNgajiPArab">—</div>
          </div>
          <button type="button" id="pfxNgajiPlayBtn" class="pfx-ngaji-round-btn">
            <i class="fa-solid fa-play" id="pfxNgajiPlayIco"></i>
          </button>
        </div>
        <div class="pfx-ngaji-seekrow">
          <span id="pfxNgajiCur">0:00</span>
          <div class="pfx-ngaji-seek-track" id="pfxNgajiSeekTrack"><div class="pfx-ngaji-seek-fill" id="pfxNgajiSeekFill"></div></div>
          <span id="pfxNgajiDur">0:00</span>
        </div>
        <div class="pfx-ngaji-navrow">
          <button type="button" id="pfxNgajiPrev" class="pfx-ngaji-nav-btn"><i class="fa-solid fa-backward-step"></i> Sebelumnya</button>
          <button type="button" id="pfxNgajiNext" class="pfx-ngaji-nav-btn">Selanjutnya <i class="fa-solid fa-forward-step"></i></button>
        </div>
      </div>
    `;
  }

  function renderList() {
    const box = document.getElementById('pfxNgajiList');
    if (!box) return;
    if (!state.filtered.length) {
      box.innerHTML = `<div class="pfx-ngaji-empty"><i class="fa-solid fa-book-quran"></i>Surah tidak ditemukan</div>`;
      return;
    }
    const activeNomor = state.idx >= 0 ? state.list[state.idx].nomor : null;
    box.innerHTML = state.filtered.map((s) => `
      <div class="pfx-ngaji-item${s.nomor === activeNomor ? ' active' : ''}" data-nomor="${s.nomor}">
        <div class="pfx-ngaji-item-num">${s.nomor}</div>
        <div class="pfx-ngaji-item-info">
          <div class="pfx-ngaji-item-name">${esc(s.nama)}</div>
          <div class="pfx-ngaji-item-meta">${s.ayat} Ayat</div>
        </div>
        <div class="pfx-ngaji-item-arab">${esc(s.arab)}</div>
        <i class="fa-solid ${s.nomor === activeNomor ? 'fa-volume-high' : 'fa-play'} pfx-ngaji-item-ico"></i>
      </div>
    `).join('');
    box.querySelectorAll('.pfx-ngaji-item').forEach((el) => {
      el.addEventListener('click', () => playByNomor(parseInt(el.dataset.nomor, 10)));
    });
  }

  function filterList(q) {
    const query = (q || '').trim().toLowerCase();
    state.filtered = !query ? state.list : state.list.filter((s) =>
      s.nama.toLowerCase().includes(query) || String(s.nomor) === query || s.arab.includes(q));
    renderList();
  }

  function playByNomor(nomor) {
    const idx = state.list.findIndex((s) => s.nomor === nomor);
    if (idx < 0 || !state.audio) return;
    state.idx = idx;
    const s = state.list[idx];

    state.audio.src = s.url;
    state.audio.play().catch(() => {});

    const nameEl = document.getElementById('pfxNgajiPName');
    const arabEl = document.getElementById('pfxNgajiPArab');
    const player = document.getElementById('pfxNgajiPlayer');
    const prevBtn = document.getElementById('pfxNgajiPrev');
    const nextBtn = document.getElementById('pfxNgajiNext');
    if (nameEl) nameEl.textContent = `${s.nomor}. ${s.nama}`;
    if (arabEl) arabEl.textContent = s.arab;
    if (player) player.style.display = 'block';
    if (prevBtn) prevBtn.disabled = idx <= 0;
    if (nextBtn) nextBtn.disabled = idx >= state.list.length - 1;

    renderList();
  }

  function togglePlay() {
    const audio = state.audio;
    if (!audio || !audio.src) return;
    if (audio.paused) audio.play().catch(() => {}); else audio.pause();
  }

  function syncPlayIcon() {
    const ico = document.getElementById('pfxNgajiPlayIco');
    if (ico) ico.className = 'fa-solid ' + (state.audio && !state.audio.paused ? 'fa-pause' : 'fa-play');
  }

  function bindEvents(mount) {
    const audio = document.createElement('audio');
    audio.preload = 'none';
    state.audio = audio;
    mount.appendChild(audio);

    audio.addEventListener('play', syncPlayIcon);
    audio.addEventListener('pause', syncPlayIcon);
    audio.addEventListener('timeupdate', () => {
      if (!audio.duration) return;
      const pct = (audio.currentTime / audio.duration) * 100;
      const fill = document.getElementById('pfxNgajiSeekFill');
      const cur = document.getElementById('pfxNgajiCur');
      if (fill) fill.style.width = pct + '%';
      if (cur) cur.textContent = fmtTime(audio.currentTime);
    });
    audio.addEventListener('loadedmetadata', () => {
      const dur = document.getElementById('pfxNgajiDur');
      if (dur) dur.textContent = fmtTime(audio.duration);
    });
    audio.addEventListener('ended', () => {
      if (state.idx >= 0 && state.idx < state.list.length - 1) playByNomor(state.list[state.idx + 1].nomor);
    });

    const search = document.getElementById('pfxNgajiSearch');
    if (search) search.addEventListener('input', () => filterList(search.value));

    const playBtn = document.getElementById('pfxNgajiPlayBtn');
    if (playBtn) playBtn.addEventListener('click', togglePlay);

    const seekTrack = document.getElementById('pfxNgajiSeekTrack');
    if (seekTrack) seekTrack.addEventListener('click', (e) => {
      if (!audio.duration) return;
      const r = seekTrack.getBoundingClientRect();
      audio.currentTime = ((e.clientX - r.left) / r.width) * audio.duration;
    });

    const prevBtn = document.getElementById('pfxNgajiPrev');
    if (prevBtn) prevBtn.addEventListener('click', () => { if (state.idx > 0) playByNomor(state.list[state.idx - 1].nomor); });
    const nextBtn = document.getElementById('pfxNgajiNext');
    if (nextBtn) nextBtn.addEventListener('click', () => { if (state.idx < state.list.length - 1) playByNomor(state.list[state.idx + 1].nomor); });
  }

  function renderNgaji(mount) {
    state.list = Array.isArray(window.PFX_NGAJI_DATA) ? window.PFX_NGAJI_DATA : [];
    state.filtered = state.list;
    state.idx = -1;
    state.audio = null;

    mount.innerHTML = shellHtml();

    if (!state.list.length) {
      const box = document.getElementById('pfxNgajiList');
      if (box) box.innerHTML = `<div class="pfx-ngaji-empty"><i class="fa-solid fa-triangle-exclamation"></i>Data surah tidak ada — pastikan tools/ngaji-data.js dimuat sebelum tools/ngaji.js</div>`;
      return;
    }
    renderList();
    bindEvents(mount);
  }

  function register() {
    if (typeof window.PretvfxToolsRegister === 'function') {
      window.PretvfxToolsRegister('ngaji', (mount) => renderNgaji(mount));
      console.log('[Ngaji] ✅ ngaji terdaftar');
    } else {
      console.error('[Ngaji] ❌ window.PretvfxToolsRegister tidak ada');
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', register);
  else register();
})();